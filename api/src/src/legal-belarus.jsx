function Md({text}){
  return text.split("\n").map((l,i)=>{
    if(["📌","📜","🗺️","🏛️","⏰","💡"].some(e=>l.startsWith(e)))
      return <div key={i} style={{marginTop:i>0?13:0,marginBottom:3,fontWeight:700,fontSize:12,color:G,letterSpacing:".04em"}}>{l}</div>;
    if(l.trim()==="---") return <div key={i} style={{borderTop:"1px solid rgba(201,168,76,.1)",margin:"10px 0"}}/>;
    if(/^\d+\./.test(l)) return <div key={i} style={{paddingLeft:12,marginBottom:2,color:"#e0d4b8",fontSize:13,lineHeight:1.6}}>{l}</div>;
    if(l.startsWith("⚠️")) return <div key={i} style={{marginTop:9,padding:"5px 10px",background:"rgba(201,168,76,.07)",borderLeft:`3px solid ${G}`,color:"#a89060",fontSize:11,borderRadius:"0 4px 4px 0",fontStyle:"italic"}}>{l}</div>;
    if(!l.trim()) return <div key={i} style={{height:3}}/>;
    return <div key={i} style={{color:"#cdc0a4",fontSize:13,lineHeight:1.7}}>{l}</div>;
  });
}

