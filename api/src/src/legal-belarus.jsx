// ─── VOICE BUTTON ─────────────────────────────────────────────────────────────
function VoiceBtn({onResult,disabled}){
  const [active,setActive]=useState(false);
  const recRef=useRef(null);
  function toggle(){
    if(active){recRef.current?.stop();setActive(false);return;}
    const SR=window.SpeechRecognition||window.webkitSpeechRecognition;
    if(!SR){alert("Голосовой ввод не поддерживается. Используйте Chrome.");return;}
    const rec=new SR();
    rec.lang="ru-RU";rec.continuous=false;rec.interimResults=false;
    rec.onresult=e=>{onResult(e.results[0][0].transcript);};
    rec.onerror=()=>setActive(false);
    rec.onend=()=>setActive(false);
    recRef.current=rec;rec.start();setActive(true);
  }
  return(
    <button onClick={toggle} disabled={disabled} title={active?"Стоп":"Голосовой ввод"}
      style={{width:42,height:42,background:active?"linear-gradient(135deg,#e05050,#a03030)":`linear-gradient(135deg,${G},#8a6820)`,border:"none",borderRadius:8,cursor:"pointer",fontSize:18,display:"flex",alignItems:"center",justifyContent:"center",boxShadow:active?"0 0 14px rgba(220,60,60,.6)":`0 2px 12px rgba(201,168,76,.28)`,transition:"all .2s",flexShrink:0,opacity:disabled?.4:1,animation:active?"voice-pulse 1s ease-in-out infinite":"none"}}>
      {active?"⏹️":"🎤"}
    </button>
  );
}

